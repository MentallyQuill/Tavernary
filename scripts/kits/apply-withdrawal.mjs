import { appendFile, readFile, rename, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

import { normalizeKitWithdrawalManifest } from "../../src/features/kits/kit-withdrawal-manifest.mjs";

const WITHDRAWAL_MANIFEST_HEADING = "Kit withdrawal manifest";
const WITHDRAWAL_RETURN_URL = "https://tavernary.org/help/withdraw-kit/";
const KIT_ID_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/u;

export function applyKitWithdrawal({ kit, actorId, now }) {
  if (kit.author.github_user_id !== actorId) {
    throw new Error("Only the Kit author may withdraw this Kit.");
  }
  if (kit.status === "withdrawn") {
    return kit;
  }
  return { ...kit, status: "withdrawn", withdrawn_at: now };
}

export async function fetchWithdrawalIssue({
  repository,
  issueNumber,
  request,
}) {
  if (!repository || !Number.isInteger(issueNumber) || issueNumber <= 0) {
    throw new Error("A valid Kit withdrawal issue number is required.");
  }
  const issue = await request(`/repos/${repository}/issues/${issueNumber}`);
  return issue;
}

function renderedJson(value) {
  const fenced = value.match(/^```(?:json)?\s*\r?\n([\s\S]*?)\r?\n```$/iu);
  return fenced?.[1] ?? value;
}

function collectManifest(body = "") {
  let value;
  let duplicate = false;
  for (const section of String(body).split(/^### /mu).slice(1)) {
    const [heading, ...content] = section.split(/\r?\n/u);
    if (heading.trim() !== WITHDRAWAL_MANIFEST_HEADING) continue;
    if (value !== undefined) {
      duplicate = true;
      continue;
    }
    value = content.join("\n").trim();
  }
  return { value: value ?? "", duplicate };
}

function validKitId(value) {
  return typeof value === "string" &&
    value.length <= 120 &&
    KIT_ID_PATTERN.test(value)
    ? value
    : null;
}

export function parseKitWithdrawalIssue(body = "") {
  const { value, duplicate } = collectManifest(body);
  if (duplicate) {
    return {
      valid: false,
      errors: [
        "Kit withdrawal issue contains a duplicate recognized form heading.",
      ],
    };
  }
  if (!value || /^_No response_$/iu.test(value)) {
    return {
      valid: false,
      errors: [
        "This issue needs the complete Kit withdrawal manifest generated by Tavernary.",
      ],
    };
  }

  let candidate;
  try {
    candidate = JSON.parse(renderedJson(value));
  } catch {
    return {
      valid: false,
      errors: ["Kit withdrawal manifest is not valid JSON."],
    };
  }
  const validation = normalizeKitWithdrawalManifest(candidate);
  if (!validation.valid) {
    return {
      valid: false,
      errors: validation.errors,
      kitId: validKitId(candidate?.kit_id),
    };
  }
  return validation;
}

function returnUrl(kitId) {
  if (!kitId) return WITHDRAWAL_RETURN_URL;
  const target = new URL(WITHDRAWAL_RETURN_URL);
  target.searchParams.set("kit", kitId);
  return target.toString();
}

function needsInformation(errors, kitId = null) {
  return {
    status: "needs-information",
    errors,
    returnUrl: returnUrl(kitId),
  };
}

function issueLabels(issue) {
  return new Set(
    (issue?.labels ?? [])
      .map((label) => (typeof label === "string" ? label : label?.name))
      .filter(Boolean),
  );
}

export async function processKitWithdrawal({ issue, loadKit, writeKit, now }) {
  const parsed = parseKitWithdrawalIssue(issue?.body ?? "");
  if (!parsed.valid) {
    return needsInformation(parsed.errors, parsed.kitId);
  }
  const kitId = parsed.manifest.kit_id;
  const errors = [];
  if (
    issue?.pull_request ||
    issue?.state !== "open" ||
    !issueLabels(issue).has("kit-withdrawal")
  ) {
    errors.push("Issue is not an open Kit withdrawal request.");
  }
  if (!Number.isInteger(issue?.user?.id) || issue.user.id <= 0) {
    errors.push("Kit withdrawal issue has no valid numeric author.");
  }
  if (errors.length > 0) return needsInformation(errors, kitId);

  let kit;
  try {
    kit = await loadKit(kitId);
  } catch {
    return needsInformation(
      ["The requested Kit is not available for withdrawal."],
      kitId,
    );
  }
  if (!kit || kit.id !== kitId) {
    return needsInformation(
      ["The requested Kit is not available for withdrawal."],
      kitId,
    );
  }
  if (kit.author?.github_user_id !== issue.user.id) {
    return needsInformation(
      ["Only the Kit author may withdraw this Kit."],
      kitId,
    );
  }
  if (kit.status !== "published" && kit.status !== "withdrawn") {
    return needsInformation(
      ["The requested Kit is not in a withdrawable state."],
      kitId,
    );
  }

  if (kit.status === "withdrawn") {
    return { status: "applied", kitId, changed: false };
  }
  const tombstone = applyKitWithdrawal({
    kit,
    actorId: issue.user.id,
    now,
  });
  await writeKit(kitId, tombstone);
  return { status: "applied", kitId, changed: true };
}

async function github(path, options = {}) {
  const response = await fetch(`https://api.github.com${path}`, {
    ...options,
    headers: {
      Accept: "application/vnd.github+json",
      Authorization: `Bearer ${process.env.GITHUB_TOKEN}`,
      "Content-Type": "application/json",
      "User-Agent": "Tavernary-kit-withdrawal",
      "X-GitHub-Api-Version": "2022-11-28",
      ...options.headers,
    },
  });
  if (!response.ok) {
    throw new Error(
      `GitHub ${response.status} for ${path}: ${await response.text()}`,
    );
  }
  return response.json();
}

async function main() {
  const issue = await fetchWithdrawalIssue({
    repository: process.env.GITHUB_REPOSITORY,
    issueNumber: Number(process.env.ISSUE_NUMBER),
    request: github,
  });
  const result = await processKitWithdrawal({
    issue,
    now: new Date().toISOString(),
    loadKit: async (kitId) => {
      const path = resolve("data/registry/kits", `${kitId}.json`);
      return JSON.parse(await readFile(path, "utf8"));
    },
    writeKit: async (kitId, tombstone) => {
      const path = resolve("data/registry/kits", `${kitId}.json`);
      const temporary = `${path}.tmp`;
      await writeFile(temporary, `${JSON.stringify(tombstone, null, 2)}\n`);
      await rename(temporary, path);
    },
  });
  if (result.status === "needs-information") {
    for (const error of result.errors) console.error(error);
  }
  if (!process.env.GITHUB_OUTPUT) {
    throw new Error("GITHUB_OUTPUT is required.");
  }
  const kitId =
    result.status === "applied"
      ? result.kitId
      : (new URL(result.returnUrl).searchParams.get("kit") ?? "");
  await appendFile(
    process.env.GITHUB_OUTPUT,
    `status=${result.status}\nkit_id=${kitId}\n`,
    "utf8",
  );
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  await main();
}
